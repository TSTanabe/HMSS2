from __future__ import annotations

import glob
import os

from unisul.cli.config import INTERMEDIATE_HITS_SUFFIX, Config
from unisul.core.logging import get_logger
from unisul.cross_check import search_cross_reference as search_cross_reference

log = get_logger(__name__)

"""
Stage: Reference sequence cross-check.

Validates intermediate hits by DIAMOND against reference sequences and
promotes them to trusted. Remaining hits can be promoted by optimized cutoff.
Finally, trusted and intermediate hit reports are summarized and stored.
"""


def reference_sequence_check(config: Config, epa_ng_selected_domains) -> None:
    """Perform reference sequence cross-check and cutoff promotion.

    Workflow:
      - intermdeia hits file are already generated by the initial search routine
      *Placement*
      - Placement of intermediate hit files in corresponding package
      - Promote hits to clade
      - if metagenome add taxonomy to read

      *Without placement do direct cross-check*
      - Cross-check with reference sequences using DIAMOND.
      - Promote validated candidates to trusted hits.
      - Promote remaining candidates by optimized cutoff.
      - Alternatively: promote only by optimized cutoff.

    Args:
        config: Pipeline configuration with cutoff settings and directories.

    Side Effects:
        Creates FAA, crosscheck, trusted, and intermediate hit files;
        updates SQLite with summarized reports.
    """
    # Get the list of intermediate hits to be processed
    # Collect intermediate hits
    intermediate_files = glob.glob(
        os.path.join(config.cross_check_directory, f"*{INTERMEDIATE_HITS_SUFFIX}")
    )

    intermediate_dict = {}

    for inter_file in intermediate_files:
        hmm_id = os.path.basename(inter_file).removesuffix(INTERMEDIATE_HITS_SUFFIX)

        # Keep complete HMM/domain identifier
        intermediate_dict[hmm_id] = inter_file

    log.info("Promoting cross-checked hits to trusted list")
    search_cross_reference.promote_crosschecked_hits_to_db(
        crosscheck_dir=config.cross_check_directory,
        database_path=config.database_directory,
        processes=config.cores,
    )

    return
